# No categories_data — use the module-level constant
CATEGORIES = {c['slug']: c for c in CATEGORIES_DATA}
TAGS = {t['slug']: t for t in TAGS_DATA}
GAMES_BY_SLUG = {g['slug']: g for g in BOARDGAMES_DATA}


class Command(BaseCommand):
    help = "Seed-скрипт: заполняет категории, теги и игры проверенными переводами."

    def add_arguments(self, parser):
        parser.add_argument(
            '--force',
            action='store_true',
            help='Режим force — перезаписывает ВСЕ поля (включая name_en)',
        )

    def handle(self, *args, **options):
        force = options.get('force', False)

        # ================================================================
        # 1. КАТЕГОРИИ
        # ================================================================
        self.stdout.write("=== Категории ===")
        for obj in Category.objects.all():
            slug = obj.slug
            data = CATEGORIES.get(slug)
            if not data:
                self.stdout.write(f"  ⚠ Слаг {slug!r} не найден в CATEGORIES_DATA, пропускаю")
                continue

            changed = []
            if force:
                obj.name_en = data['name_en']
                changed.append('name_en')
            if force or not obj.name_ru:
                obj.name_ru = data['name_ru']
                changed.append('name_ru')
            if force or not obj.description_ru:
                desc_ru = data.get('description_ru', '')
                obj.description_ru = desc_ru
                if desc_ru:
                    changed.append('description_ru')
                obj.description = desc_ru

            # name всегда = name_ru (DEFAULT_LANGUAGE = ru)
            if force or not obj.name:
                obj.name = obj.name_ru

            if changed:
                obj.save()
                self.stdout.write(f"  ✅ [{slug}] {data['name_en']} → {data['name_ru']} ({', '.join(changed)})")
            else:
                self.stdout.write(f"  🔸 [{slug}] уже заполнено")

        # ================================================================
        # 2. ТЕГИ
        # ================================================================
        self.stdout.write("\n=== Теги ===")
        for obj in Tag.objects.all():
            slug = obj.slug
            data = TAGS.get(slug)
            if not data:
                self.stdout.write(f"  ⚠ Слаг {slug!r} не найден в TAGS_DATA, пропускаю")
                continue

            changed = []
            if force:
                obj.name_en = data['name_en']
                changed.append('name_en')
            if force or not obj.name_ru:
                obj.name_ru = data['name_ru']
                changed.append('name_ru')
            if force or not obj.name:
                obj.name = obj.name_ru

            if changed:
                obj.save()
                self.stdout.write(f"  ✅ [{slug}] {data['name_en']} → {data['name_ru']} ({', '.join(changed)})")
            else:
                self.stdout.write(f"  🔸 [{slug}] уже заполнено")

        # ================================================================
        # 3. НАСТОЛЬНЫЕ ИГРЫ
        # ================================================================
        self.stdout.write("\n=== Настольные игры ===")
        for obj in BoardGame.objects.all():
            slug = obj.slug
            data = GAMES_BY_SLUG.get(slug)
            if not data:
                self.stdout.write(f"  ⚠ Слаг {slug!r} не найден в BOARDGAMES_DATA, пропускаю")
                continue

            changed = []
            # Названия
            if force:
                obj.title_en = data['title_en']
                obj.title_ru = data['title_ru']
                changed.extend(['title_en', 'title_ru'])
            else:
                if not obj.title_en:
                    obj.title_en = data['title_en']
                    changed.append('title_en')
                if not obj.title_ru:
                    obj.title_ru = data['title_ru']
                    changed.append('title_ru')

            # Описания
            if force:
                obj.description_ru = data.get('description_ru', '')
                obj.description_en = data.get('description_en', '')
                changed.extend(['description_ru', 'description_en'])
            else:
                if not obj.description_ru:
                    obj.description_ru = data.get('description_ru', '')
                    if data.get('description_ru'):
                        changed.append('description_ru')
                if not obj.description_en:
                    obj.description_en = data.get('description_en', '')
                    if data.get('description_en'):
                        changed.append('description_en')

            # description = description_ru (DEFAULT_LANGUAGE = ru)
            if force or not obj.description:
                obj.description = obj.description_ru

            # Остальные поля
            numeric_fields = ['min_players', 'max_players', 'play_time', 'difficulty']
            for field in numeric_fields:
                val = data.get(field)
                if val is not None:
                    setattr(obj, field, val)

            for field in ['designer', 'bgg_type']:
                val = data.get(field, '')
                if val:
                    setattr(obj, field, val)

            for field in ['is_active', 'is_visible_ru', 'is_visible_en']:
                val = data.get(field)
                if val is not None:
                    setattr(obj, field, val)

            obj.save()

            # Связи M2M — категории
            cat_slugs = data.get('categories', [])
            cats = Category.objects.filter(slug__in=cat_slugs)
            obj.categories.set(list(cats))

            # Связи M2M — теги
            tag_slugs = data.get('tags', [])
            tags = Tag.objects.filter(slug__in=tag_slugs)
            obj.tags.set(list(tags))

            if changed:
                self.stdout.write(f"  ✅ [{slug}] {data['title_ru']} ({', '.join(changed)})")
            else:
                self.stdout.write(f"  🔸 [{slug}] уже заполнено")

        self.stdout.write(self.style.SUCCESS(f"\n✅ Готово!"))